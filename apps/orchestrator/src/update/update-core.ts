/** Updating the server from inside the app — pure helpers (unit-tested). */

export type SemVer = [number, number, number];

/** `v0.1.47` / `0.1.47` → [0, 1, 47]; null for anything else (`dev`, `latest`, `0.1`). */
export function parseVersion(v: string | undefined | null): SemVer | null {
  const m = /^v?(\d{1,4})\.(\d{1,5})\.(\d{1,6})$/.exec((v ?? '').trim());
  return m ? [Number(m[1]), Number(m[2]), Number(m[3])] : null;
}

/** >0 when a is newer than b. */
export function compareVersions(a: string, b: string): number {
  const x = parseVersion(a);
  const y = parseVersion(b);
  if (!x || !y) return 0;
  for (let i = 0; i < 3; i++) if (x[i]! !== y[i]!) return x[i]! - y[i]!;
  return 0;
}

export const cleanVersion = (v: string): string => v.trim().replace(/^v/, '');

/** Single-quote a value for a POSIX shell. */
export function shq(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

export interface RunnerOptions {
  repo: string;
  version: string;
  installDir: string;
  dataDir: string;
  /** Directory for status.json / update.log. */
  stateDir: string;
}

/**
 * The shell script that performs the update. It is started DETACHED from the service (the installer restarts the service, which would
 * otherwise kill its own updater), downloads the install script of the TARGET release, runs it in bare-metal mode, and records the
 * outcome in status.json so the (new) server can report it.
 */
export function buildRunnerScript(o: RunnerOptions): string {
  const version = cleanVersion(o.version);
  if (!parseVersion(version)) throw new Error(`bad version "${o.version}"`);
  if (!/^[\w./-]+$/.test(o.repo)) throw new Error('bad repository name');
  return `#!/bin/sh
# Generated by the Aigentron server: update to v${version}. Runs detached from the service.
set -u
STATE=${shq(o.stateDir)}
VERSION=${shq(version)}
STARTED=$(date -u +%Y-%m-%dT%H:%M:%SZ)
write_status() { # state finishedAt error
  printf '{"state":"%s","version":"%s","startedAt":"%s","finishedAt":"%s","error":"%s"}\\n' "$1" "$VERSION" "$STARTED" "$2" "$3" > "$STATE/status.json.tmp" && mv "$STATE/status.json.tmp" "$STATE/status.json"
}
write_status running "" ""
TMP=$(mktemp -d)
{
  echo "== update to v$VERSION started $STARTED"
  if curl -fsSL "https://raw.githubusercontent.com/${o.repo}/v$VERSION/install.sh" -o "$TMP/install.sh" \\
     && INSTALL_MODE=bare INSTALL_DIR=${shq(o.installDir)} DATA_DIR=${shq(o.dataDir)} VERSION="$VERSION" sh "$TMP/install.sh" </dev/null; then
    echo "== update finished OK"
    OK=1
  else
    echo "== update FAILED — the previous release stays in place (see above)"
    OK=0
  fi
} >> "$STATE/update.log" 2>&1
rm -rf "$TMP"
NOW=$(date -u +%Y-%m-%dT%H:%M:%SZ)
if [ "$OK" = 1 ]; then write_status ok "$NOW" ""; else write_status failed "$NOW" "the installer failed — see the log"; fi
`;
}

export interface ReleaseInfo {
  version: string;
  notes: string;
  url: string;
  publishedAt: string | null;
}

/** GitHub's "latest release" JSON → what we show. */
export function parseRelease(json: unknown): ReleaseInfo | null {
  const j = (json && typeof json === 'object' ? json : {}) as { tag_name?: unknown; body?: unknown; html_url?: unknown; published_at?: unknown };
  const version = typeof j.tag_name === 'string' ? cleanVersion(j.tag_name) : '';
  if (!parseVersion(version)) return null;
  return {
    version,
    notes: typeof j.body === 'string' ? j.body.slice(0, 6000) : '',
    url: typeof j.html_url === 'string' ? j.html_url : '',
    publishedAt: typeof j.published_at === 'string' ? j.published_at : null,
  };
}
