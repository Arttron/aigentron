/**
 * Clearing the checkouts of finished work. A task's own copy of the repository (its git worktree) is deleted when the work is DONE — and only when nothing
 * would be lost. Pure: the facts come in, a decision comes out (what is deleted, whether the branch goes with it, and the reason in words).
 */
export type CleanupMode = 'off' | 'merged' | 'merged_or_done';

export const CLEANUP_MODES: readonly CleanupMode[] = ['off', 'merged', 'merged_or_done'];
export const isCleanupMode = (v: unknown): v is CleanupMode => typeof v === 'string' && (CLEANUP_MODES as readonly string[]).includes(v);

export interface CleanupPolicy {
  /** off · merged (as soon as its work is in the base branch) · merged_or_done (that, or `doneDays` after the task is done / cancelled) */
  mode: CleanupMode;
  doneDays: number;
}

export const DEFAULT_CLEANUP_POLICY: CleanupPolicy = { mode: 'merged_or_done', doneDays: 3 };

export interface CheckoutFacts {
  status: string;
  /** when the task last changed (ms) — for a finished task, when it finished */
  finishedAt: number | null;
  /** a lead waiting for its subtasks */
  awaitingSubtasks: boolean;
  /** uncommitted or untracked files in the checkout; null = could not be checked */
  dirty: boolean | null;
  /** files git ignores that are NOT build output (a `.env`, local notes, generated keys): they would be lost with the folder */
  preciousIgnored?: boolean;
  /** commits of the task's branch that the base branch lacks; null = could not be told */
  ahead: number | null;
  /** the branch's head is on a remote; null = could not be told */
  pushed: boolean | null;
  /** the base has the same changes as commits of their own (a rebase merge) */
  appliedByPatch: boolean;
  /** the task's pull request was merged (GitHub); null = not known */
  prMerged: boolean | null;
}

export interface CleanupDecision {
  remove: boolean;
  /** the local branch goes too (only when the work is in the base branch, so no commit is lost) */
  deleteBranch: boolean;
  /** why, in words (what the person reads) */
  reason: string;
}

const LIVE = ['queued', 'running', 'needs_approval'];
const DAY = 86_400_000;

const keep = (reason: string): CleanupDecision => ({ remove: false, deleteBranch: false, reason });

export function decideCleanup(policy: CleanupPolicy, f: CheckoutFacts, now = Date.now()): CleanupDecision {
  if (policy.mode === 'off') return keep('cleaning up finished work is switched off');
  if (LIVE.includes(f.status) || f.awaitingSubtasks) return keep('the task is being worked on');
  // what is not committed is lost with the folder
  if (f.dirty === null) return keep('the checkout could not be checked for unsaved work');
  if (f.dirty) return keep('the checkout has uncommitted changes');
  if (f.preciousIgnored) return keep('the checkout holds ignored files that are not build output (like a .env)');

  const inBase = f.ahead === 0 || f.appliedByPatch || f.prMerged === true;
  if (inBase) {
    return { remove: true, deleteBranch: true, reason: f.prMerged === true ? 'its pull request was merged' : f.ahead === 0 ? 'everything on its branch is already in the base branch' : 'its changes are in the base branch' };
  }
  if (policy.mode === 'merged') return keep('its work is not merged yet');

  if (f.status !== 'done' && f.status !== 'cancelled') return keep('the task is not finished');
  if (f.ahead === null || f.pushed === null) return keep('could not tell whether its commits are saved elsewhere');
  const waitUntil = f.finishedAt === null ? null : f.finishedAt + policy.doneDays * DAY;
  if (waitUntil !== null && now < waitUntil) return keep(`finished recently — cleaned ${policy.doneDays} day(s) after it finished`);
  if (!f.pushed) return keep(`${f.ahead} commit(s) exist only here (not merged, not pushed)`);
  // finished, clean, its commits are on the remote: the checkout can go; the branch stays (its commits are not in the base branch)
  return { remove: true, deleteBranch: false, reason: `finished ${policy.doneDays}+ day(s) ago; its commits are on the remote` };
}

/** Folders / files that are regenerated by a build or an install: losing them loses nothing. */
const REGENERABLE = new Set(['node_modules', 'dist', 'build', 'out', '.next', '.nuxt', '.turbo', '.cache', '.parcel-cache', '.vite', 'coverage', 'target', '.venv', 'venv', '__pycache__', '.pytest_cache', '.mypy_cache', '.gradle', '.ds_store', '.eslintcache', '.svelte-kit', '.angular']);

/** From `git status --porcelain --ignored` lines: the ignored paths (`!! path`) that are not build output. */
export function preciousIgnoredPaths(porcelain: string): string[] {
  const out: string[] = [];
  for (const line of porcelain.split('\n')) {
    if (!line.startsWith('!! ')) continue;
    const path = line.slice(3).trim().replace(/\/$/, '');
    if (!path) continue;
    const parts = path.split('/');
    const regenerable = parts.some((p) => REGENERABLE.has(p.toLowerCase())) || /\.(log|pyc|tsbuildinfo)$/i.test(path);
    if (!regenerable) out.push(path);
  }
  return out;
}

/** Lines of `git status --porcelain` that are real changes (everything but the ignored entries). */
export const hasUncommitted = (porcelain: string): boolean => porcelain.split('\n').some((l) => l.trim() && !l.startsWith('!! '));
